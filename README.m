# 🚨 Detector de Spam con Machine Learning

Este repositorio contiene un clasificador de texto inteligente capaz de identificar de forma automática si un mensaje recibido es correo no deseado (Spam) o un mensaje legítimo.

## 🛠️ Tecnologías utilizadas
* **Python 3**
* **Scikit-Learn** (Algoritmo Naive Bayes)
* **CountVectorizer** (Procesamiento de texto)

## 📈 Aplicación en el mundo real
Este modelo sirve para optimizar sistemas de mensajería, soporte técnico automatizado y filtrado de correos masivos en empresas.
